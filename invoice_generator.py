from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.units import mm
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer
)


def generate_invoice_pdf(invoice: dict, output_path: str, issuer: dict):
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("InvoiceTitle", parent=styles["Title"],
                                  fontSize=22, spaceAfter=2)
    label_style = ParagraphStyle("Label", parent=styles["Normal"],
                                  textColor=colors.HexColor("#64748B"), fontSize=9)
    normal = styles["Normal"]

    doc = SimpleDocTemplate(output_path, pagesize=A4,
                             topMargin=25*mm, bottomMargin=20*mm,
                             leftMargin=20*mm, rightMargin=20*mm)
    story = []

    # Header: issuer info + INVOICE title/number side by side
    issuer_lines = [f"<b>{issuer.get('company') or issuer.get('name', '')}</b>"]
    if issuer.get("company_reg"):
        issuer_lines.append(f"Reg. No. {issuer['company_reg']}")
    if issuer.get("company_address"):
        issuer_lines.append(issuer["company_address"].replace("\n", "<br/>"))
    issuer_lines.append(issuer.get("email", ""))

    header_data = [[
        Paragraph("<br/>".join(issuer_lines), normal),
        Paragraph(f"<para align='right'><font size=20><b>INVOICE</b></font>"
                  f"<br/>{invoice['invoice_no']}</para>", normal),
    ]]
    header_table = Table(header_data, colWidths=[90*mm, 70*mm])
    header_table.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story.append(header_table)
    story.append(Spacer(1, 10*mm))

    # Bill-to / dates
    meta_data = [[
        Paragraph(f"<b>Bill To</b><br/>{invoice['client_name']}"
                  f"<br/>{invoice.get('client_email', '')}", normal),
        Paragraph(f"<b>Issue Date</b><br/>{invoice['issue_date']}", normal),
        Paragraph(f"<b>Due Date</b><br/>{invoice['due_date']}", normal),
    ]]
    meta_table = Table(meta_data, colWidths=[70*mm, 45*mm, 45*mm])
    meta_table.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP")]))
    story.append(meta_table)
    story.append(Spacer(1, 10*mm))

    # Line items table
    rows = [["Description", "Qty", "Unit Price (RM)", "Amount (RM)"]]
    for item in invoice["line_items"]:
        qty = float(item["qty"])
        price = float(item["unit_price"])
        amount = qty * price
        rows.append([
            item["description"],
            f"{qty:g}",
            f"{price:,.2f}",
            f"{amount:,.2f}",
        ])
    rows.append(["", "", "Total", f"RM {invoice['total']:,.2f}"])

    items_table = Table(rows, colWidths=[85*mm, 20*mm, 30*mm, 30*mm])
    items_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E293B")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("ALIGN", (1, 0), (-1, -1), "RIGHT"),
        ("ALIGN", (0, 0), (0, -1), "LEFT"),
        ("GRID", (0, 0), (-1, -2), 0.5, colors.HexColor("#CBD5E1")),
        ("FONTNAME", (2, -1), (3, -1), "Helvetica-Bold"),
        ("LINEABOVE", (2, -1), (-1, -1), 1, colors.HexColor("#1E293B")),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(items_table)

    if invoice.get("payment_url"):
        story.append(Spacer(1, 6*mm))
        pay_style = ParagraphStyle("PayLink", parent=normal,
                                    textColor=colors.HexColor("#2563EB"),
                                    fontSize=11, alignment=2)  # right-aligned
        story.append(Paragraph(
            f'<link href="{invoice["payment_url"]}">'
            f'<b>Pay this invoice online →</b></link>', pay_style
        ))

    if invoice.get("notes"):
        story.append(Spacer(1, 10*mm))
        story.append(Paragraph("<b>Notes</b>", normal))
        story.append(Paragraph(invoice["notes"], normal))

    story.append(Spacer(1, 15*mm))
    story.append(Paragraph(
        "This invoice was generated by FinMan.", label_style
    ))

    doc.build(story)
    return output_path